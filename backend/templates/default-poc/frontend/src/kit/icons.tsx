// First match wins, so the specific words come before the general ones.
const GUESSES: [RegExp, string][] = [
  [/defect|risk|incident|overdue|late|fail|error|complaint|breach|churn/i, "alert"],
  [/revenue|sales|cost|spend|budget|price|profit|margin|cash|invoice|€|\$|eur|usd/i, "money"],
  [/rate|ratio|percent|%|share|conversion|utili[sz]ation|yield/i, "percent"],
  [/customer|employee|user|candidate|staff|headcount|people|member|patient|student/i, "users"],
  [/order|basket|purchase|checkout/i, "cart"],
  [/stock|inventory|item|sku|unit|product/i, "package"],
  [/deliver|ship|freight|route|fleet/i, "truck"],
  [/time|hour|day|duration|lead time|latency|age/i, "clock"],
  [/energy|kwh|power|electric/i, "bolt"],
  [/temperature|°c|°f/i, "thermometer"],
  [/score|rating|csat|nps|satisfaction/i, "star"],
  [/target|goal|quota|plan/i, "target"],
  [/complete|done|closed|resolved|approved|passed|on.?time/i, "check"],
  [/site|plant|store|branch|office|location/i, "building"],
  [/region|country|market/i, "globe"],
  [/growth|trend|change/i, "trend"],
];

export function guessIcon(label: string): string {
  return GUESSES.find(([pattern]) => pattern.test(label))?.[1] ?? "activity";
}

/** A named icon; an unknown name falls back to a guess from the label. */
export function Icon({ name, label = "", size = 18 }: { name?: string; label?: string; size?: number }) {
  const key = name && name in PATHS ? name : guessIcon(label);
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[key]}
    </svg>
  );
}

